    public static boolean english() {
        InterfaceModule ui = Modules.get(InterfaceModule.class);
        String choice = ui == null ? "Automatisch" : ui.language.get();
        if (choice.equals("English")) {
            return true;
        } else if (choice.equals("Deutsch")) {
            return false;
        } else {
            String code = Minecraft.getInstance().options.languageCode;
            return code == null || !code.startsWith("de");
        }
    }

    /** The English text for a German one, whatever language is chosen (the German one if there is none). */
    public static String en(String german) {
        String en = german == null ? null : EN.get(german);
        return en != null ? en : german;
    }

    public static String t(String german) {
        if (german != null && english()) {
            String en = EN.get(german);
            return en != null ? en : german;
        } else {
            return german;
        }
    }

